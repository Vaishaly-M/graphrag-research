"""Generate KG counts and structural checks from immutable exports and live Neo4j."""
import argparse
import json
from collections import Counter
from datetime import datetime
from pathlib import PurePosixPath

import yaml

from src.ingest.storage import ROOT, digest, read_rows, save
from src.ingest.snapshots import allowed_path
from src.kg.build import DIRECTIONS, LABELS
from src.kg.neo4j_store import connect, query


def validate(nodes, edges):
    errors = []
    ids = {r['id']:r for r in nodes}
    if len(ids) != len(nodes): errors.append('duplicate node IDs')
    if len({r['id'] for r in edges}) != len(edges): errors.append('duplicate relationship IDs')
    degrees = Counter()
    for r in nodes:
        if not r.get('repo') or not r.get('snapshot'): errors.append('missing provenance: '+r['id'])
        if r['label'] == 'File':
            if not r.get('path') or not allowed_path(r['path']) or PurePosixPath(r['path']).is_absolute():
                errors.append('bad/missing file path: '+r['id'])
        required={'Repository':['commit_date'],'Commit':['timestamp','author_date'],
                  'Issue':['created_at','updated_at','observed_at'],'PullRequest':['created_at','updated_at','observed_at']}
        for field in required.get(r['label'],[]):
            if not r.get(field):errors.append('missing date '+field+': '+r['id'])
        dates={}
        for key in ['timestamp', 'author_date', 'created_at', 'updated_at', 'closed_at', 'merged_at', 'commit_date', 'observed_at']:
            if r.get(key):
                try:
                    date = datetime.fromisoformat(r[key].replace('Z', '+00:00'))
                    if date.tzinfo is None: raise ValueError('timezone missing')
                    dates[key]=date
                except (ValueError, TypeError): errors.append('bad date '+key+': '+r['id'])
        for field in ['updated_at','closed_at','merged_at']:
            if 'created_at' in dates and field in dates and dates['created_at']>dates[field]:
                errors.append('date ordering '+field+': '+r['id'])
    for e in edges:
        if e['start'] not in ids or e['end'] not in ids:
            errors.append('orphan relationship: '+e['id']); continue
        a, b = ids[e['start']], ids[e['end']]
        if DIRECTIONS.get(e['type']) != (a['label'], b['label']): errors.append('bad direction: '+e['id'])
        if a['repo'] != b['repo'] or e['repo'] != a['repo']: errors.append('cross-repo relationship: '+e['id'])
        degrees[a['id']] += 1; degrees[b['id']] += 1
    errors.extend('isolated entity: '+r['id'] for r in nodes if not degrees[r['id']])
    return errors


def run(live=False):
    config = yaml.safe_load((ROOT/'configs/snapshots.yaml').read_text()); dataset=config['dataset_id']
    root=ROOT/'data/graph_exports'/dataset
    nodes=read_rows(root/'nodes.jsonl');edges=read_rows(root/'relationships.jsonl')
    errors=validate(nodes,edges)
    manifest=json.loads((root/'manifest.json').read_text())
    for name, key in [('nodes.jsonl','nodes_sha256'),('relationships.jsonl','relationships_sha256')]:
        if digest(root/name)!=manifest[key]:errors.append('export hash mismatch '+name)
    live_status='NOT RUN'
    if live:
        try:
            with connect() as driver:
                ns=query(driver,'MATCH (n) WHERE n.dataset=$dataset RETURN n.id AS id, n.label AS label',dataset=dataset)
                es=query(driver,'MATCH (a)-[r]->(b) WHERE r.dataset=$dataset RETURN r.id AS id,a.id AS start,b.id AS end,type(r) AS type',dataset=dataset)
                if Counter((r['id'],r['label']) for r in ns)!=Counter((r['id'],r['label']) for r in nodes):errors.append('live node mismatch')
                if Counter((r['id'],r['start'],r['end'],r['type']) for r in es)!=Counter((r['id'],r['start'],r['end'],'DL_'+r['type']) for r in edges):errors.append('live relationship/direction mismatch')
                offline_indexes=[r['name'] for r in query(driver,'SHOW INDEXES YIELD name,state RETURN name,state') if r['name'].startswith('dl_') and r['state']!='ONLINE']
                if offline_indexes:errors.append('indexes not ONLINE')
            live_status='PASS' if not errors else 'FAIL'
        except Exception as exc:
            live_status='BLOCKED: '+type(exc).__name__;errors.append(live_status)
    report=['# KG validation', '', 'Generated by `python -m analysis.validate_data_layer --live`.', '',
            f'Dataset: `{dataset}`. Structural export: {"PASS" if not validate(nodes,edges) else "FAIL"}. Live Neo4j: {live_status}.', '',
            'Identity counts are repo-scoped; the same human may have multiple unlinked identities. Historical graph labels are excluded. API metadata is observed state, not reconstructed historical Git state.', '',
            '| Repository | '+' | '.join(LABELS)+' | Total |','|---|'+'---:|'*(len(LABELS)+1)]
    for repo in sorted({r['repo'] for r in nodes})+[None]:
        c=Counter(r['label'] for r in nodes if repo is None or r['repo']==repo)
        report.append('| '+(repo or '**Total**')+' | '+' | '.join(str(c[k]) for k in LABELS)+f' | {sum(c.values())} |')
    types=sorted(DIRECTIONS)
    report.extend(['','| Repository | '+' | '.join(types)+' | Total |','|---|'+'---:|'*(len(types)+1)])
    for repo in sorted({r['repo'] for r in nodes})+[None]:
        c=Counter(r['type'] for r in edges if repo is None or r['repo']==repo)
        report.append('| '+(repo or '**Total**')+' | '+' | '.join(str(c[k]) for k in types)+f' | {sum(c.values())} |')
    report.extend(['',f'Excluded modification links outside retained tree: {manifest["scope_counts"].get("modifications_outside_retained_tree",0)}.', '',
                   'Checks: unique IDs, provenance, orphan endpoints/isolated nodes, parseable timezone dates, date order, retained paths, typed relationship directions and repository scope. Live mode compares every entity/relationship identity and direction and checks index readiness.', '',
                   'Errors: '+str(len(errors))]+['- '+e for e in errors[:50]])
    (ROOT/'reports/kg_validation.md').write_text('\n'.join(report)+'\n',encoding='utf-8')
    save(root/'validation.json',dict(passed=not errors and live, structural_passed=not validate(nodes,edges), live=live_status, errors=errors,
                                   node_counts=dict(Counter(r['label'] for r in nodes)), relationship_counts=dict(Counter(r['type'] for r in edges))))
    print('Structural/live errors:',len(errors),'nodes',len(nodes),'edges',len(edges),'live',live_status)
    return not errors


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--live',action='store_true');args=parser.parse_args()
    raise SystemExit(0 if run(args.live) else 1)
