"""Single generated source of benchmark counts and isolation checks."""
import argparse
import csv
import json
from collections import Counter

import yaml

from src.ingest.storage import ROOT, digest, read_rows, save


def load(path):return read_rows(path) if path.exists() else []


def generate(require_complete=False):
    root=ROOT/'data/benchmark';config=yaml.safe_load((ROOT/'configs/splits.yaml').read_text())
    groups={code:sum((load(root/kind/f'{split}.jsonl') for split in ['development','validation','test']),[])
            for code,kind in [('T','template'),('P','paraphrase')]}
    groups['H']=load(root/'human/normalized.jsonl');verified=load(root/'human/test.jsonl')
    groups['U']=load(root/'unanswerable/probes.jsonl');groups['N']=load(root/'unanswerable/near_misses.jsonl')
    human_ids={r['question_id'] for r in groups['H']};human_text={r['question'] for r in groups['H']}
    families=[set(config[s]['families']) for s in ['development','validation','test']]
    assert not families[0]&families[1] and not (families[0]|families[1])&families[2]
    t_lookup={r['question_id']:r for r in groups['T']}
    for code,rows in groups.items():
        assert len({r['question_id'] for r in rows})==len(rows)
        for r in rows:
            if r['split']!='test':
                assert r['repo']!=config['unseen_repo'] and r['question_id'] not in human_ids and r['question'] not in human_text
                assert not any(':apache/airflow:' in e for e in r.get('gold_evidence_ids',[]))
            if code in {'T','P'}:
                assert r['template_family'] in config[r['split']]['families']
                assert r['repo'] in config[r['split']]['repos']
                assert r['gold_source']=='executed_neo4j' and r['gold_complete']
            if code=='P':
                original=t_lookup[r['source_question_id']]
                from analysis.paraphrase_questions import GOLD_FIELDS
                assert all(r[key]==original[key] for key in GOLD_FIELDS)
                assert not r['paraphrase_checks']['missing_protected']
                assert not r['paraphrase_checks']['missing_previously_named_gold_entities']
                assert r['paraphrase_model'].startswith('qwen') and r['split']=='test'
    spec=config['question_sets']['H'];assert digest(ROOT/spec['source'])==spec['source_sha256']
    with (ROOT/spec['source']).open(encoding='utf-8-sig',newline='') as stream:source={r['question_id']:r for r in csv.DictReader(stream)}
    assert len(groups['H'])==len(source)==100
    for r in groups['H']:
        original=source[r['source_question_id']]
        assert r['question']==original['question'] and r['author_id']==original['author_persona'] and r['split']=='test'
    assert len({r['author_id'] for r in groups['H']})==5
    assert all(r['human_gold_verified'] and r['eligible'] and r['source_sha256']==spec['source_sha256'] for r in verified)
    assert len(groups['U'])==len(groups['N'])==40
    assert {r['pair_id'] for r in groups['U']}=={r['pair_id'] for r in groups['N']}
    assert all(not r['answerable'] and r['expected_answer']=='not found' for r in groups['U'])
    assert all(r['answerable'] and r['gold_entities'] for r in groups['N'])
    p_manifest=root/'paraphrase/generation_manifest.json'
    p_complete=p_manifest.exists() and json.loads(p_manifest.read_text()).get('complete') and len(groups['P'])==sum(r['split']=='test' for r in groups['T'])
    if p_complete:assert json.loads(p_manifest.read_text())['source_sha256']==digest(root/'template/test.jsonl')
    if require_complete and not p_complete:raise ValueError('Paraphrase collection incomplete')
    lines=['# Benchmark statistics', '', 'Generated by `python -m analysis.benchmark_stats`; do not hand-edit counts.', '',
           'T, P and H are separate sets. U (unanswerable) and N (matched answerable near-misses) are separate test probes. '
           'H counts below describe normalized submissions, not approved gold. Only human/test.jsonl is scored after verification.', '',
           '| Set | Records | Eligible now | Excluded/pending |', '|---|---:|---:|---:|']
    for code,rows in groups.items():
        eligible=len(verified) if code=='H' else len(rows)
        lines.append(f'| {code} | {len(rows)} | {eligible} | {len(rows)-eligible} |')
    lines.extend(['',f'P collection: {"complete" if p_complete else "in progress"}. '
                  f'H normalized entity-set approval: {len(verified)}/{len(groups["H"])}; {len(groups["H"])-len(verified)} excluded from entity scoring until approved.',
                  '',f'H source SHA-256: `{spec["source_sha256"]}`. Original wording and all five author IDs are preserved.',
                  '', '## Counts by dimension'])
    status_counts=Counter(r.get('supplied_status','unspecified') for r in groups['H'])
    lines.extend(['',f'User-confirmed human-verified supplied prose answers: {sum(r.get("supplied_gold_human_verified",False) for r in groups["H"])}. '
                  'This is distinct from approved normalized entity sets eligible for scoring.'])
    lines.extend(['','### Supplied H verification labels','',
                  'These are source labels, not approval of normalized entity sets or snapshot evidence.', '',
                  '| Source status | Count |','|---|---:|'])
    lines.extend(f'| {status} | {count} |' for status,count in sorted(status_counts.items()))
    dimensions=[('repo','Repository'),('category','Category'),('hop_count','Hop bucket'),('gold_route','Gold route'),('answerable','Answerable'),('split','Split')]
    for field,title in dimensions:
        def value(r):
            v=r.get(field)
            if v is None:return 'pending verification'
            if field=='hop_count' and v>=3:return '3+'
            return str(v).lower() if isinstance(v,bool) else str(v)
        counts={code:Counter(value(r) for r in rows) for code,rows in groups.items()}
        values=sorted(set().union(*(c.keys() for c in counts.values())))
        lines.extend(['',f'### {title}','',f'| {title} | T | P | H | U | N |','|---|---:|---:|---:|---:|---:|'])
        for v in values:lines.append('| '+v+' | '+' | '.join(str(counts[c][v]) for c in groups)+' |')
    missing=sum(not r['paraphrase_checks']['all_gold_entities_named'] for r in groups['P'])
    prior_named=sum(bool(r['paraphrase_checks']['gold_entities_named_in_source']) for r in groups['P'])
    lines.extend(['','## Verification and interpretation','',
        f'- Literal full-gold-name check: {missing} P questions do not name every answer entity. {prior_named} source T questions named at least one gold entity. Previously named entities and all protected input identifiers are preserved. Gold answers absent from T wording are not injected into P as hints.',
        '- A 50-item seeded P spot-check sheet is written after collection completes. Automatic checks do not establish semantic equivalence; human review remains needed.',
        '- H proposed routes and evidence are annotation aids, not approved gold. Unknown answerability remains unknown; only exact named-entity absence queries support a draft unanswerable proposal. All unverified H questions are excluded.',
        '- Gold Cypher is executed for every T/U/N item. Hop count is the number of relationship traversals in the declared gold-query path (4 is reported in 3+). Text/line questions use one repository-to-file edge.',
        '- Dependency questions concern explicitly named manifest files or import declaration lines, not a complete resolved dependency graph. Empty import/declaration lists are answerable negative facts, not missing-evidence probes.',
        '- Route labels describe intended evidence modality. They are not empirical best-route outcomes or an upper-bound oracle.',
        '- Family allocation is globally disjoint; category coverage is intentionally different in development/validation. All seven categories occur in T test. Airflow and all human submissions are test-only.',
        '- Queries and absence statements apply to retained files and bounded sampled history/API observations. They do not establish absence from the entire upstream repository history.',
        '', 'Construction validation: '+('PASS; human verification pending' if p_complete else 'IN PROGRESS: P collection pending')])
    (ROOT/'reports/benchmark_stats.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    split_lines=['# Single source of truth: split counts','','Generated by `python -m analysis.benchmark_stats` from `configs/splits.yaml` and actual JSONL records.', '',
        '| Set | Split | Planned | Observed | Eligible | Airflow |','|---|---|---:|---:|---:|---:|']
    for code in ['T','P','H','U','N']:
        for split in ['development','validation','test']:
            planned=len(config[split]['repos'])*sum(config.get('family_quotas',{}).get(f,config['questions_per_repo_family']) for f in config[split]['families'])
            if code=='P' and split!='test':planned=0
            if code=='H':planned=100 if split=='test' else 0
            if code in {'U','N'}:planned=40 if split=='test' else 0
            rows=[r for r in groups[code] if r['split']==split];eligible=len(verified) if code=='H' and split=='test' else (0 if code=='H' else len(rows))
            split_lines.append(f'| {code} | {split} | {planned} | {len(rows)} | {eligible} | {sum(r["repo"]==config["unseen_repo"] for r in rows)} |')
    split_lines.extend(['','H observed counts are normalized submissions; eligible counts require manual approval. P is test-only and inherits T gold and groups. U/N are not pooled with T/P/H.', '',
                        'The preliminary six-family pool is archived under data/benchmark/archive/preliminary-20261014. These current counts supersede its 40/20/90 plan.', '',
                        'Split/isolation validation: PASS'])
    (ROOT/'reports/split_counts.md').write_text('\n'.join(split_lines)+'\n',encoding='utf-8')
    save(root/'benchmark_validation.json',dict(passed=bool(p_complete),human_verified=len(verified),human_excluded=len(groups['H'])-len(verified),
         counts={k:len(v) for k,v in groups.items()},airflow_in_development_validation=0,human_used_for_development=False,
         human_source_sha256=spec['source_sha256']))
    print('Benchmark counts:',{k:len(v) for k,v in groups.items()},'H scoring-ready:',len(verified),'P complete:',bool(p_complete))


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--require-complete',action='store_true');a=p.parse_args();generate(a.require_complete)
