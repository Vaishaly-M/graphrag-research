"""Verify both index formats, provenance and repository-scoped retrieval."""
import json
from collections import Counter

import yaml

from src.ingest.storage import ROOT, digest, read_rows, save
from src.retrieval.snapshot_index import SnapshotIndex


def main(directory=None, report_name='index_validation.md'):
    import faiss
    config=yaml.safe_load((ROOT/'configs/snapshots.yaml').read_text());dataset=config['dataset_id']
    directory=directory or ROOT/'data/indexes'/dataset
    store=SnapshotIndex(directory)
    graph=ROOT/'data/graph_exports'/dataset/'nodes.jsonl'
    assert store.manifest['source_nodes_sha256']==digest(graph)
    ids={r['id']:r for r in read_rows(graph)}
    index=faiss.read_index(str(directory/'index.faiss'))
    assert index.ntotal==len(store.docs)==len(store.bm['lengths'])
    assert len({r['id'] for r in store.docs})==len(store.docs)
    assert store.bm['chunk_sha256']==digest(directory/'chunks.jsonl')
    for row in store.docs:
        source=ids[row['entity_id']]
        assert row['repo']==source['repo'] and row['snapshot']==source['snapshot']
        assert 'path' in row and row['commit']
    for repo in store.manifest['by_repo']:
        results=store.bm25('repository component issue',repo)
        assert results and all(r['repo']==repo for r in results)
        position=next(i for i,row in enumerate(store.docs) if row['repo']==repo)
        vector=index.reconstruct(position).reshape(1,-1)
        scores,positions=index.search(vector,min(10,index.ntotal))
        assert scores[0,0]>0.999
    assert dict(Counter(r['repo'] for r in store.docs))==store.manifest['by_repo']
    probe=store.faiss('synthetic data integrity probe','synthetic-org/platform',k=3)
    assert len(probe)==3 and all(r['repo']=='synthetic-org/platform' for r in probe)
    save(directory/'validation.json',dict(passed=True,chunks=index.ntotal,repositories=store.manifest['by_repo'],
         manifest_sha256=digest(directory/'manifest.json')))
    report=['# Retrieval index validation', '', 'Generated by `python -m analysis.validate_indexes`.', '',
            'Status: PASS. FAISS and BM25 share the same hashed chunk stream.', '',
            '| Repository | Chunks |', '|---|---:|']
    report.extend(f'| {repo} | {count} |' for repo,count in sorted(store.manifest['by_repo'].items()))
    report.extend([f'| **Total** | **{index.ntotal}** |', '',
                   'Checks: artifact/source hashes, unique chunk IDs, snapshot/path/commit provenance, '
                   'matching document counts, per-repository BM25 filtering, FAISS vector self-search, '
                   'and a synthetic-string query through the pinned encoder with repository filtering. '
                   'These are data-integrity checks, not question-answering evaluations.'])
    (ROOT/'reports'/report_name).write_text('\n'.join(report)+'\n',encoding='utf-8')
    print('Index validation PASS:',index.ntotal,'shared chunks')


if __name__=='__main__':main()
