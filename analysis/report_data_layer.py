"""Generate the clean-rebuild Part 1B handoff from validated artifacts."""
import json
from collections import Counter

import yaml

from src.ingest.storage import ROOT, digest, read_rows


def main():
    config=yaml.safe_load((ROOT/'configs/snapshots.yaml').read_text())
    dataset=config['dataset_id']
    graph=ROOT/'data/graph_exports'/dataset
    indexes=ROOT/'data/indexes'/dataset
    kg=json.loads((graph/'validation.json').read_text())
    iv=json.loads((indexes/'validation.json').read_text())
    im=json.loads((indexes/'manifest.json').read_text())
    assert kg['passed'] and kg['live']=='PASS' and iv['passed']
    assert iv['manifest_sha256']==digest(indexes/'manifest.json')
    assert im['source_nodes_sha256']==digest(graph/'nodes.jsonl')
    assert iv['chunks']==im['chunk_count']
    splits=yaml.safe_load((ROOT/'configs/splits.yaml').read_text())
    from analysis.build_splits import report_counts
    report_counts(splits)
    manifest=json.loads((ROOT/'data/benchmark/split_manifest.json').read_text())
    assert manifest['config_sha256']==digest(ROOT/'configs/splits.yaml')
    assert manifest['export_sha256']==digest(graph/'nodes.jsonl')
    rows=read_rows(graph/'nodes.jsonl')
    totals=Counter(r['repo'] for r in rows)
    lines=['# Clean rebuild: Part 1B', '', 'Generated by `python -m analysis.report_data_layer`.', '',
           f'Dataset: `{dataset}`. Data-layer acceptance: PASS.', '',
           'This report covers the new data layer, not the older diagnostic Phase 1B experiment. '
           'No next-phase experiments or held-out question answering were run.', '',
           '| Repository | Entities | Index chunks |', '|---|---:|---:|']
    for repo,count in sorted(totals.items()):
        lines.append(f'| {repo} | {count} | {im["by_repo"][repo]} |')
    lines.extend([f'| **Total** | **{len(rows)}** | **{im["chunk_count"]}** |', '',
                  f'Relationships: {sum(kg["relationship_counts"].values())}. '
                  'Structural and live Neo4j validation passed; shared FAISS/BM25 validation passed.', '',
                  '| Question set | Development | Validation | Test | Status |', '|---|---:|---:|---:|---|'])
    counts=[]
    for split in ['development','validation','test']:
        questions=read_rows(ROOT/'data/benchmark/template'/f'{split}.jsonl')
        assert [r['question_id'] for r in questions]==manifest['membership'][split]
        if split!='test':assert all(r['repo']!=splits['unseen_repo'] for r in questions)
        counts.append(len(questions))
    values=' | '.join(map(str,counts))
    p_counts=[len(read_rows(ROOT/'data/benchmark/paraphrase'/f'{s}.jsonl')) for s in ['development','validation','test']]
    h_count=len(read_rows(ROOT/'data/benchmark/human/normalized.jsonl')) if (ROOT/'data/benchmark/human/normalized.jsonl').exists() else 0
    h_verified=len(read_rows(ROOT/'data/benchmark/human/test.jsonl'))
    lines.extend([f'| T | {values} | Generated and eligible |',
                  '| P | '+' | '.join(map(str,p_counts))+' | Collected; see benchmark statistics for completion |',
                  f'| H | 0 | 0 | {h_count} | {h_verified} verified; remaining submissions excluded pending human review |', '',
                  'Airflow is absent from every new development/validation question artifact. '
                  'Template families are globally disjoint. Unverified human submissions are not scored. '
                  'Current question counts and collection status are in reports/benchmark_stats.md.', '',
                  'Scope: bounded commit/API samples, with API observation dates distinct from Git commit dates. '
                  'See [KG validation](kg_validation.md), [index validation](index_validation.md), '
                  '[split counts](split_counts.md) and [decisions](../DECISIONS.md).'])
    (ROOT/'reports/data_layer_part1b.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    print('Part 1B data-layer acceptance PASS')


if __name__=='__main__':main()
