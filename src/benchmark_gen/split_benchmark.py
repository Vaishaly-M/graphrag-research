"""
Partition the 300-question benchmark into development, validation, and
hidden-test sets (Guide Sections 4-6).

Splits combine three signals:

  - repository holdout: one repository's questions go to hidden-test only,
    so routing/threshold decisions made on dev/val cannot have been tuned
    on that repository's names or examples.
  - template-novelty: for each category with more than one template shape,
    the rarest template_name is reserved for hidden-test only, so hidden
    -test always contains at least some query shapes the router/thresholds
    were never tuned against.
  - stratified-by-category sampling for the remaining rows, so dev,
    validation, and the rest of hidden-test each keep roughly the original
    category balance.

The hidden-test file written for runners (hidden_test_questions.*) has
every gold-answer-revealing field removed -- including `answerable`, which
would otherwise let a system score perfectly on abstention questions by
just reading the label instead of reasoning about it. The full rows
(gold included) are kept separately in hidden_test_answer_key.* for
evaluation only; do not load that file as a --benchmark-file for any
system run whose numbers will be reported.

Run:
    python -m src.benchmark_gen.split_benchmark
"""

from __future__ import annotations

import argparse
import csv
import json
import random
from collections import defaultdict
from pathlib import Path
from typing import Any

import yaml

from src.common import ROOT, config_get, read_jsonl, write_jsonl

SPLIT_SEED = int(config_get("seeds.benchmark_generation", 42))

DEV_FRACTION = 0.25
VALIDATION_FRACTION = 0.25
# The remaining ~0.50 of non-holdout rows go to hidden-test.

GOLD_ONLY_FIELDS = {
    "ground_truth",
    "expected_answer",
    "expected_entities",
    "required_facts",
    "expected_relations",
    "expected_path",
    "gold_evidence",
    "cypher",
    "params",
    "answerable",
}


def load_configured_repo_slugs(config_path: str = "config/repos.yaml") -> set[str]:
    """
    Slugs of the real, mined GitHub repositories (as opposed to the
    synthetic-org/platform repo generated by src/synthetic_gen/generate.py).
    """
    path = ROOT / config_path

    if not path.exists():
        return set()

    config = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    return {item["slug"] for item in config.get("repositories", [])}


def pick_holdout_repo(rows: list[dict[str, Any]], rng: random.Random) -> str:
    """
    Choose the repository whose questions are entirely reserved for
    hidden-test. Restricted to the real, configured GitHub repositories --
    the synthetic-org/platform repo is deliberately excluded because it is
    small (contributes only a handful of questions) and deterministically
    templated, so holding it out is a weak test of cross-repository
    generalization compared to holding out a real project.
    """
    repos = {row["source_repo"] for row in rows}
    configured = load_configured_repo_slugs()
    eligible = sorted(repos & configured) if configured else sorted(repos)

    if not eligible:
        eligible = sorted(repos)

    return rng.choice(eligible)


def pick_holdout_templates(
    rows: list[dict[str, Any]], rng: random.Random
) -> dict[str, str]:
    """For each category with more than one template shape, reserve its
    rarest template_name for hidden-test only."""
    by_category: defaultdict[str, defaultdict[str, int]] = defaultdict(
        lambda: defaultdict(int)
    )

    for row in rows:
        by_category[row["category"]][row["template_name"]] += 1

    holdout: dict[str, str] = {}

    for category, counts in by_category.items():
        if len(counts) < 2:
            continue  # Only one template shape in this category.

        min_count = min(counts.values())
        rarest = sorted(name for name, count in counts.items() if count == min_count)
        holdout[category] = rng.choice(rarest)

    return holdout


def stratified_split(
    rows: list[dict[str, Any]], rng: random.Random
) -> tuple[list[dict[str, Any]], list[dict[str, Any]], list[dict[str, Any]]]:
    dev: list[dict[str, Any]] = []
    validation: list[dict[str, Any]] = []
    test: list[dict[str, Any]] = []

    by_category: defaultdict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in rows:
        by_category[row["category"]].append(row)

    for _category, category_rows in by_category.items():
        shuffled = list(category_rows)
        rng.shuffle(shuffled)

        n = len(shuffled)
        dev_count = min(round(n * DEV_FRACTION), n)
        validation_count = min(round(n * VALIDATION_FRACTION), n - dev_count)

        dev.extend(shuffled[:dev_count])
        validation.extend(shuffled[dev_count:dev_count + validation_count])
        test.extend(shuffled[dev_count + validation_count:])

    return dev, validation, test


def strip_gold_fields(row: dict[str, Any]) -> dict[str, Any]:
    return {key: value for key, value in row.items() if key not in GOLD_ONLY_FIELDS}


def write_jsonl_and_csv(base_path: Path, rows: list[dict[str, Any]]) -> None:
    write_jsonl(base_path.with_suffix(".jsonl"), rows)

    if not rows:
        return

    structured = {
        key for key in rows[0] if isinstance(rows[0][key], (dict, list))
    }

    csv_path = base_path.with_suffix(".csv")
    fieldnames = list(rows[0].keys())

    with csv_path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()

        for row in rows:
            serialized = dict(row)

            for field in structured:
                if field in serialized:
                    serialized[field] = json.dumps(
                        serialized[field], ensure_ascii=False
                    )

            writer.writerow(serialized)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Split benchmark_300 into dev/validation/hidden-test."
    )
    parser.add_argument("--input", default="data/benchmark/benchmark_300.jsonl")
    parser.add_argument("--output-dir", default="data/benchmark/splits")
    parser.add_argument(
        "--holdout-repo",
        default=None,
        help=(
            "Force a specific repository to be entirely held out for "
            "hidden-test. Defaults to a seeded deterministic choice."
        ),
    )
    args = parser.parse_args()

    rng = random.Random(SPLIT_SEED)

    input_path = ROOT / args.input
    rows = read_jsonl(input_path)

    if not rows:
        raise FileNotFoundError(f"No benchmark rows found at {input_path}")

    holdout_repo = args.holdout_repo or pick_holdout_repo(rows, rng)
    holdout_templates = pick_holdout_templates(rows, rng)

    forced_test: list[dict[str, Any]] = []
    remaining: list[dict[str, Any]] = []

    for row in rows:
        is_holdout_repo = row["source_repo"] == holdout_repo
        is_holdout_template = (
            holdout_templates.get(row["category"]) == row["template_name"]
        )

        if is_holdout_repo or is_holdout_template:
            forced_test.append(row)
        else:
            remaining.append(row)

    dev, validation, stratified_test = stratified_split(remaining, rng)
    hidden_test = forced_test + stratified_test

    output_dir = ROOT / args.output_dir
    output_dir.mkdir(parents=True, exist_ok=True)

    write_jsonl_and_csv(output_dir / "dev", dev)
    write_jsonl_and_csv(output_dir / "validation", validation)
    write_jsonl_and_csv(output_dir / "hidden_test_answer_key", hidden_test)

    runner_facing = [strip_gold_fields(row) for row in hidden_test]
    write_jsonl_and_csv(output_dir / "hidden_test_questions", runner_facing)

    repo_holdout_count = sum(
        1 for row in forced_test if row["source_repo"] == holdout_repo
    )
    template_holdout_count = len(forced_test) - repo_holdout_count

    manifest = {
        "seed": SPLIT_SEED,
        "holdout_repo": holdout_repo,
        "holdout_templates_by_category": holdout_templates,
        "counts": {
            "dev": len(dev),
            "validation": len(validation),
            "hidden_test": len(hidden_test),
            "hidden_test_from_repo_holdout": repo_holdout_count,
            "hidden_test_from_template_holdout": template_holdout_count,
            "hidden_test_from_stratified_remainder": len(stratified_test),
        },
        "gold_fields_stripped_from_hidden_test_questions": sorted(GOLD_ONLY_FIELDS),
    }

    (output_dir / "split_manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8"
    )

    print("Benchmark split")
    print("-" * 60)
    print(f"Holdout repository : {holdout_repo}")
    print(f"Holdout templates  : {holdout_templates}")
    print(f"Dev                : {len(dev)}")
    print(f"Validation         : {len(validation)}")
    print(f"Hidden test        : {len(hidden_test)}")
    print(f"  from repo holdout     : {repo_holdout_count}")
    print(f"  from template holdout : {template_holdout_count}")
    print(f"  from stratified split : {len(stratified_test)}")
    print("\nRunner-facing hidden-test questions have these fields removed:")
    print(f"  {sorted(GOLD_ONLY_FIELDS)}")

    guide_min, guide_max = 60, 80
    for split_name, split_rows in (("dev", dev), ("validation", validation)):
        if len(split_rows) < guide_min:
            print(
                f"\nWarning: {split_name} has {len(split_rows)} questions, "
                f"below the guide's suggested {guide_min}-{guide_max}. "
                f"Holding out '{holdout_repo}' removed a large share of the "
                "remaining pool before the dev/validation split ran. If you "
                "need a larger dev/validation set, rerun with "
                "--holdout-repo set to a smaller repository."
            )

    print(f"\nWrote splits to: {output_dir}")
    print(
        "\nIMPORTANT: only dev/ and validation/ may be used for tuning "
        "routing, thresholds, fusion weights, or prompts. Do not open "
        "hidden_test_answer_key.* until the system is frozen (Guide "
        "Section 4.1 / 6.3)."
    )


if __name__ == "__main__":
    main()
